-- 中文输入法兜底：普通模式下把全角标点当英文用
--
-- 解决什么问题：
--   用中文输入法时想敲 `:wq` 退出，打出来的是全角 `：wq`，vim 不认。
--   中文态的 `；` `，` `（` 同理，全都进不了命令。
--
-- 为什么在 nvim 里兜底、而不是去改输入法热键：
--   输入法的中英切换键各家用各自的机制（豆包/水杉都不给绑右 ⌘ 这类纯修饰键），
--   改不动。而全角标点在【普通模式】下本来就没有任何 vim 含义，
--   映射掉零风险，还能覆盖所有输入法，一劳永逸。
--
-- 注意：只映射普通模式。插入模式不动 —— 中文标点是正常输入需求。

local pairs_map = {
  ["："] = ":",
  ["；"] = ";",
  ["，"] = ",",
  ["。"] = ".",
  ["！"] = "!",
  ["？"] = "?",
  ["（"] = "(",
  ["）"] = ")",
}

for full, ascii in pairs(pairs_map) do
  vim.keymap.set("n", full, ascii, {
    desc = "全角 " .. full .. " 当 " .. ascii .. " 用（中文输入法兜底）",
  })
end
